
from __future__ import annotations

import hashlib
import logging
import os
from pathlib import Path
from typing import Any

import chromadb
from dotenv import load_dotenv
from google import genai

# ---------------------------------------------------------
# Configuration
# ---------------------------------------------------------

BASE_DIR = Path(__file__).resolve().parent
load_dotenv(BASE_DIR / ".env")

API_KEY = os.getenv("GEMINI_API_KEY", "").strip()

GENERATION_MODEL = os.getenv(
    "GEMINI_MODEL",
    "gemini-3.5-flash-lite",
).strip()

GENERATION_FALLBACKS = [
    model.strip()
    for model in os.getenv(
        "GEMINI_MODEL_FALLBACKS",
        "gemini-3.6-flash",
    ).split(",")
    if model.strip()
]

EMBEDDING_MODEL = os.getenv(
    "GEMINI_EMBEDDING_MODEL",
    "gemini-embedding-001",
).strip()

KNOWLEDGE_DIR = Path(
    os.getenv("KNOWLEDGE_DIR", str(BASE_DIR / "knowledge"))
)

CHROMA_DIR = Path(
    os.getenv("CHROMA_DIR", str(BASE_DIR / "chroma_db"))
)

COLLECTION_NAME = "printing_knowledge"
TOP_K = max(1, int(os.getenv("RAG_TOP_K", "4")))
CHUNK_SIZE = max(200, int(os.getenv("RAG_CHUNK_SIZE", "1000")))
CHUNK_OVERLAP = max(
    0,
    min(
        int(os.getenv("RAG_CHUNK_OVERLAP", "150")),
        CHUNK_SIZE - 1,
    ),
)

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)


class RAGAssistant:
    def __init__(self) -> None:
        if not API_KEY:
            raise RuntimeError(
                "GEMINI_API_KEY is missing from your .env file."
            )

        self.client = genai.Client(api_key=API_KEY)

        CHROMA_DIR.mkdir(parents=True, exist_ok=True)

        self.chroma_client = chromadb.PersistentClient(
            path=str(CHROMA_DIR)
        )

        self.collection = self._get_collection()
        self.last_generation_model: str | None = None

    # -----------------------------------------------------
    # ChromaDB collection
    # -----------------------------------------------------

    def _get_collection(self):
        existing = self.chroma_client.get_collection(
            name=COLLECTION_NAME
        ) if COLLECTION_NAME in [
            item.name for item in self.chroma_client.list_collections()
        ] else None

        # Never reuse vectors generated by a different embedding model.
        if (
            existing is not None
            and existing.metadata
            and existing.metadata.get("embedding_model")
            != EMBEDDING_MODEL
        ):
            logger.warning(
                "Embedding model changed; rebuilding ChromaDB collection."
            )
            self.chroma_client.delete_collection(COLLECTION_NAME)
            existing = None

        if existing is not None:
            return existing

        return self.chroma_client.create_collection(
            name=COLLECTION_NAME,
            metadata={
                "hnsw:space": "cosine",
                "embedding_model": EMBEDDING_MODEL,
            },
        )

    # -----------------------------------------------------
    # Read and chunk knowledge documents
    # -----------------------------------------------------

    @staticmethod
    def _chunk_text(text: str) -> list[str]:
        text = text.strip()
        if not text:
            return []

        chunks: list[str] = []
        start = 0

        while start < len(text):
            end = min(start + CHUNK_SIZE, len(text))

            if end < len(text):
                boundary = text.rfind(" ", start, end)
                if boundary > start:
                    end = boundary

            chunk = text[start:end].strip()
            if chunk:
                chunks.append(chunk)

            if end >= len(text):
                break

            start = max(start + 1, end - CHUNK_OVERLAP)

        return chunks

    def _load_documents(self) -> list[dict[str, Any]]:
        if not KNOWLEDGE_DIR.exists():
            raise FileNotFoundError(
                f"Knowledge directory not found: {KNOWLEDGE_DIR}. "
                "Set KNOWLEDGE_DIR in .env to the correct folder."
            )

        files = sorted(KNOWLEDGE_DIR.rglob("*.txt"))

        if not files:
            raise FileNotFoundError(
                f"No .txt documents found in {KNOWLEDGE_DIR}"
            )

        documents: list[dict[str, Any]] = []

        for file_path in files:
            content = file_path.read_text(encoding="utf-8-sig")
            source = str(file_path.relative_to(KNOWLEDGE_DIR))

            for chunk_index, chunk in enumerate(
                self._chunk_text(content)
            ):
                stable_id = hashlib.sha256(
                    f"{source}:{chunk_index}".encode("utf-8")
                ).hexdigest()

                documents.append(
                    {
                        "id": stable_id,
                        "source": source,
                        "chunk_index": chunk_index,
                        "text": chunk,
                    }
                )

        if not documents:
            raise RuntimeError("No readable knowledge chunks found.")

        return documents

    # -----------------------------------------------------
    # Gemini embeddings
    # -----------------------------------------------------

    def _embed_text(self, text: str) -> list[float]:
        response = self.client.models.embed_content(
            model=EMBEDDING_MODEL,
            contents=text,
        )

        if not response.embeddings:
            raise RuntimeError(
                "Gemini returned an empty embedding."
            )

        return response.embeddings[0].values

    # -----------------------------------------------------
    # Synchronize documents with persistent ChromaDB
    # -----------------------------------------------------

    def _sync_index(self) -> None:
        documents = self._load_documents()

        existing = self.collection.get(
            include=["documents"]
        )

        existing_ids = existing["ids"]
        existing_texts = dict(
            zip(existing_ids, existing["documents"] or [])
        )

        current_ids = {item["id"] for item in documents}
        stale_ids = [
            item_id for item_id in existing_ids
            if item_id not in current_ids
        ]

        if stale_ids:
            self.collection.delete(ids=stale_ids)

        # Only embed chunks that are new or whose text has changed.
        changed = [
            item for item in documents
            if existing_texts.get(item["id"]) != item["text"]
        ]

        batch_size = 20

        for start in range(0, len(changed), batch_size):
            batch = changed[start:start + batch_size]

            vectors = [
                self._embed_text(item["text"])
                for item in batch
            ]

            self.collection.upsert(
                ids=[item["id"] for item in batch],
                embeddings=vectors,
                documents=[item["text"] for item in batch],
                metadatas=[
                    {
                        "source": item["source"],
                        "chunk_index": item["chunk_index"],
                    }
                    for item in batch
                ],
            )

        logger.info(
            "ChromaDB ready: %s chunks; %s new/changed chunks embedded.",
            self.collection.count(),
            len(changed),
        )

    # -----------------------------------------------------
    # Retrieve relevant chunks from ChromaDB
    # -----------------------------------------------------

    def retrieve(
        self,
        question: str,
        top_k: int = TOP_K,
    ) -> list[dict[str, Any]]:
        self._sync_index()

        query_embedding = self._embed_text(question)
        result_count = min(
            max(1, top_k),
            self.collection.count(),
        )

        results = self.collection.query(
            query_embeddings=[query_embedding],
            n_results=result_count,
            include=["documents", "metadatas", "distances"],
        )

        retrieved: list[dict[str, Any]] = []

        ids = results["ids"][0]
        texts = results["documents"][0]
        metadata = results["metadatas"][0]
        distances = results["distances"][0]

        for item_id, text, meta, distance in zip(
            ids, texts, metadata, distances
        ):
            retrieved.append(
                {
                    "id": item_id,
                    "source": meta["source"],
                    "chunk_index": meta["chunk_index"],
                    "text": text,
                    # Chroma cosine distance: lower is more similar.
                    "score": round(1.0 - float(distance), 4),
                }
            )

        return retrieved

    # -----------------------------------------------------
    # Gemini generation with fallback models
    # -----------------------------------------------------

    def _generate_with_fallback(
        self,
        prompt: str,
    ) -> tuple[str, str, list[str]]:
        candidates = list(
            dict.fromkeys(
                [GENERATION_MODEL, *GENERATION_FALLBACKS]
            )
        )
        errors: list[str] = []

        for model in candidates:
            try:
                response = self.client.models.generate_content(
                    model=model,
                    contents=prompt,
                )

                answer_text = getattr(response, "text", None)

                if not answer_text or not answer_text.strip():
                    raise RuntimeError(
                        "Gemini returned an empty response."
                    )

                self.last_generation_model = model

                return answer_text.strip(), model, errors

            except Exception as exc:
                errors.append(f"{model}: {exc}")
                logger.warning(
                    "Generation model %s failed: %s",
                    model,
                    exc,
                )

        raise RuntimeError(
            "All configured Gemini text-generation models failed. "
            + " | ".join(errors)
        )

    # -----------------------------------------------------
    # Grounded RAG answer
    # -----------------------------------------------------

    def answer(self, question: str) -> dict[str, Any]:
        question = question.strip()

        if not question:
            raise ValueError("Enter a question.")

        retrieved = self.retrieve(question)

        context = "\n\n".join(
            f"[Source: {item['source']}]\n{item['text']}"
            for item in retrieved
        )

        prompt = f"""
You are the Printing Services Assistant.

Answer the question using only the printing knowledge context below.

Rules:
- Do not invent prices, shop policies, or live order statuses.
- If the context does not answer the question, say that the available
  information does not establish the answer.
- Black-and-white printing costs INR 2 per printed side.
- Colour printing costs INR 8 per printed side.
- Double-sided printing reduces paper usage, not the charge per
  printed side.
- Optional binding costs INR 30 per copy.
- Customers should retain their order reference for collection.
- You cannot access live print jobs, upload documents, or send jobs
  to a printer.
- Keep answers clear and concise.

KNOWLEDGE CONTEXT:
{context}

USER QUESTION:
{question}

Answer:
""".strip()

        answer_text, model_used, errors = (
            self._generate_with_fallback(prompt)
        )

        sources = list(
            dict.fromkeys(item["source"] for item in retrieved)
        )

        return {
            "answer": answer_text,
            "sources": sources,
            "retrieved_chunks": retrieved,
            "model_used": model_used,
            "embedding_model_used": EMBEDDING_MODEL,
            "fallbacks_tried": errors,
            "vector_store": "ChromaDB",
        }


# ---------------------------------------------------------
# Lazy singleton used by Flask
# ---------------------------------------------------------

_assistant: RAGAssistant | None = None


def get_rag_assistant() -> RAGAssistant:
    global _assistant

    if _assistant is None:
        _assistant = RAGAssistant()

    return _assistant


def answer_question(question: str) -> dict[str, Any]:
    return get_rag_assistant().answer(question)
